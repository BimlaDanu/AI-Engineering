"""Every number the README quotes about a run must match the run it cites.

The README says of the scorecard that "both come from the same reduction, so they
cannot disagree". They can, and they did: the table claimed retrieval 100% (12/12)
and accuracy 3 of 10 while ``reports/scorecard.json`` held 83% (10/12) and 5 of 12,
and the supporting line quoted a mean precision of 0.52 against a measured 0.4773.
Nothing failed, because nothing was checking -- a scorecard is regenerated by
``make evals`` and the prose about it is edited by hand, so they drift apart every
time a suite is re-run and the drift is invisible until a reader opens both.

These read the artefact and search the README for what it should say. They are not
a substitute for running the suite; they are what stops the report of a suite from
outliving it.
"""

from __future__ import annotations

import json
import re
from typing import Any

import pytest

from src.agent.graph import answer_toolkit, pipeline_nodes
from src.ui.status import PROJECT_ROOT

README = PROJECT_ROOT / "README.md"
SCORECARD = PROJECT_ROOT / "reports" / "scorecard.json"


def _scorecard() -> dict[str, Any]:
    """Load the last scorecard, skipping the suite when none has been written.

    Returns:
        The parsed summary ``make evals`` wrote.
    """
    if not SCORECARD.is_file():
        pytest.skip("no scorecard yet; run `make evals`")
    return json.loads(SCORECARD.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def readme() -> str:
    """The README with its markdown emphasis stripped.

    Searched as plain text, because the claim under test is the figure and not
    how it is marked up: the table writes ``**83%** (10/12)`` and a check that
    demanded the asterisks would break on a bolding change and pass on a wrong
    number, which is exactly backwards.

    Returns:
        The text, with ``*`` and ``_`` removed.
    """
    return README.read_text(encoding="utf-8").replace("*", "").replace("_", "")


STOCHASTIC_SUITES = frozenset({"Retrieval"})
"""Suites whose score legitimately moves between two runs of the same code.

Retrieval expands the query with a live model call, so the same corpus and the same
twelve questions do not give the same score twice: the two marginal cases turn on
whether expansion reaches them. Measured across four runs in one afternoon the pass
rate was 11/12 or 12/12 and mean precision ran 0.57 to 0.66.

That is a fact about the measurement, not a defect, and pinning it to the digit made
this file fail on every ``make evals`` -- which trains a reader to edit the number
until the build goes green, the exact habit the pin exists to prevent. So a
stochastic suite is held to the *neighbourhood* of what was measured and a
deterministic one is still held to the digit.
"""

CASES_TOLERANCE = 1
"""How many cases a stochastic suite's quoted score may sit away from the measured one."""

MEAN_TOLERANCE = 0.12
"""How far a quoted retrieval mean may sit from the measured one.

Wider than the spread observed across four runs, so an honest document passes, and far
narrower than the distance to a figure somebody made up.
"""


def test_each_suite_score_is_quoted_as_measured(readme: str) -> None:
    """The README's score table matches the scorecard's own percentages.

    Exactly, for a suite that measures the same thing twice running. Within one case
    for a suite that does not -- see :data:`STOCHASTIC_SUITES`.

    Args:
        readme: The README text.
    """
    for suite in _scorecard()["scores"]:
        if not suite["ran"]:
            continue
        quoted = f"{suite['percent']} ({suite['passed']}/{suite['total']})"
        if suite["name"] not in STOCHASTIC_SUITES:
            assert quoted in readme, (
                f"{suite['name']} scored {quoted} in reports/scorecard.json and the "
                f"README does not say so anywhere"
            )
            continue
        claimed = [
            int(passed)
            for passed, total in re.findall(r"\((\d+)/(\d+)\)", readme)
            if int(total) == suite["total"]
        ]
        assert claimed, (
            f"{suite['name']} is scored out of {suite['total']} and the README quotes "
            f"no score with that denominator"
        )
        assert any(abs(value - suite["passed"]) <= CASES_TOLERANCE for value in claimed), (
            f"{suite['name']} scored {suite['passed']}/{suite['total']} and the README "
            f"quotes {claimed}, none of them within {CASES_TOLERANCE} case of it"
        )


@pytest.mark.parametrize(
    ("field", "phrase"),
    [
        ("mean_precision", "mean precision@4"),
        ("mean_reciprocal_rank", "mean reciprocal rank"),
    ],
)
def test_retrieval_supporting_numbers_are_quoted_as_measured(
    readme: str, field: str, phrase: str
) -> None:
    """Precision and reciprocal rank are quoted near the value measured.

    Near rather than at: both are means over a search whose query expansion is a model
    call, so they move between runs. See :data:`STOCHASTIC_SUITES` for why holding
    them to the digit was the wrong pin.

    The figure is read out of the sentence that names the metric, so this checks the
    number the README actually attaches to that phrase rather than whether the digits
    appear anywhere in the document.

    Args:
        readme: The README text.
        field: The scorecard key to check.
        phrase: The wording the README introduces that figure with.
    """
    measured = _scorecard()["retrieval"][field]
    quoted = [float(value) for value in re.findall(rf"{re.escape(phrase)} (\d\.\d+)", readme)]
    assert quoted, f"the README never writes {phrase!r} followed by a figure"
    assert all(abs(value - measured) <= MEAN_TOLERANCE for value in quoted), (
        f"retrieval.{field} is {measured:.4f} and the README quotes {quoted}, "
        f"further than {MEAN_TOLERANCE} from it"
    )


