def test_the_readme_documents_every_node_the_graph_has() -> None:
    """The "Node by node" table and the graph name the same seventeen nodes.

    The README states a node count in one place and lists the nodes in another,
    and the two drifted: it claimed seventeen while its own table described
    sixteen, with ``converge`` -- the node that draws the curves -- missing. A
    reader counting the table would have found the count wrong and had no way to
    tell which half was.

    Reads the file rather than taking the ``readme`` fixture, which strips markdown
    emphasis -- and here the emphasis is the syntax being matched.
    """
    import re

    from src.agent.graph import build_graph

    raw = README.read_text(encoding="utf-8")
    block = raw[raw.index("<summary><b>Node by node</b>") :]
    block = block[: block.index("</details>")]
    listed = set(re.findall(r"\| \*\*([a-z_]+)\*\* \|", block))
    actual = {name for name in build_graph().get_graph().nodes if not name.startswith("__")}

    assert listed == actual, (
        f"undocumented nodes: {sorted(actual - listed)}; "
        f"documented but absent from the graph: {sorted(listed - actual)}"
    )
    assert f"{len(actual)} nodes" in raw, (
        f"the graph has {len(actual)} nodes and the README states some other number"
    )


def test_the_mermaid_diagram_draws_every_node_the_graph_has() -> None:
    # The README said "seventeen nodes exist" directly above a diagram with sixteen
    # boxes: `converge` was missing. A hand-drawn picture of a generated structure
    # goes stale the first time the structure changes, and nothing counted the boxes.
    import re

    from src.agent.graph import pipeline_nodes

    diagram = re.search(r"```mermaid\n(.*?)```", README.read_text(encoding="utf-8"), re.DOTALL)
    assert diagram is not None, "the README lost its graph diagram"
    drawn = set(re.findall(r"^    ([a-z_]+)\[", diagram.group(1), re.MULTILINE))
    missing = set(pipeline_nodes()) - drawn

    assert not missing, f"the diagram does not draw: {', '.join(sorted(missing))}"


def test_the_drawn_graph_figure_covers_every_node_too() -> None:
    # Two pictures of one graph, and they have to agree. The script raises at draw
    # time if its layout is short a node, but `make figures` is not part of `make
    # check`, so a node added today would not go red until somebody redrew. Read by
    # parsing rather than importing: scripts/ is not a package, and importing one of
    # its modules from here has mypy see the same file under two module names.
    import ast

    from src.agent.graph import pipeline_nodes

    tree = ast.parse((PROJECT_ROOT / "scripts/draw_agent_graph.py").read_text(encoding="utf-8"))
    drawn: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "LAYOUT":
            assert isinstance(node.value, ast.Dict)
            drawn = {
                key.value
                for key in node.value.keys
                if isinstance(key, ast.Constant) and isinstance(key.value, str)
            }

    assert drawn, "the figure's LAYOUT table could not be read"
    assert drawn == set(pipeline_nodes())


def test_the_workflow_figure_counts_agree_with_the_code_they_describe() -> None:
    # The master slide states "7 pages" and "17 nodes" in its label column. Both are
    # counts of things that change, printed into a picture nobody re-reads.
    import ast

    from src.agent.graph import pipeline_nodes
    from src.ui import panels

    tree = ast.parse(
        (PROJECT_ROOT / "scripts/draw_project_workflow.py").read_text(encoding="utf-8")
    )
    claims: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "BANDS":
            assert isinstance(node.value, ast.Tuple)
            for band in node.value.elts:
                assert isinstance(band, ast.Tuple)
                claims += [
                    item.value
                    for item in band.elts
                    if isinstance(item, ast.Constant) and isinstance(item.value, str)
                ]

    assert claims, "the figure's BANDS table could not be read"
    assert f"{len(panels.PAGES)} pages" in " | ".join(claims), "the page count is wrong"
    assert f"{len(pipeline_nodes())} nodes" in " | ".join(claims), "the node count is wrong"
