def test_the_readme_states_one_test_count_and_one_doctest_count(readme: str) -> None:
    """The suite's size is quoted in several places, and they must agree.

    Not pinned to the real total, which changes with every test added and would
    make this a chore rather than a check. What it catches is the failure that
    actually happened: the README said 2703 tests in three places, 2717 in a
    fourth, 132 doctests in one and 133 in another. A reader cannot tell which is
    true, and a document that disagrees with itself is evidence against every
    other number in it.

    Args:
        readme: The README text.
    """
    import re

    def stated(unit: str) -> set[int]:
        found = re.findall(r"(\d[\d\u202f ,]*\d|\d)\s+" + unit + r"\b", readme)
        return {int(re.sub(r"[^\d]", "", value)) for value in found}

    counted = stated("tests")
    assert len(counted) <= 1, f"the README states {sorted(counted)} as its test count"
    docs = stated("doctests")
    assert len(docs) <= 1, f"the README states {sorted(docs)} as its doctest count"


